CREATE DATABASE IF NOT EXISTS calzados_sa;
USE calzados_sa;

DROP TABLE IF EXISTS horario;
DROP TABLE IF EXISTS vendido;
DROP TABLE IF EXISTS provee;
DROP TABLE IF EXISTS tiene;
DROP TABLE IF EXISTS dia;
DROP TABLE IF EXISTS franco;
DROP TABLE IF EXISTS venta;
DROP TABLE IF EXISTS vendedor;
DROP TABLE IF EXISTS minorista;
DROP TABLE IF EXISTS mayorista;
DROP TABLE IF EXISTS cliente;
DROP TABLE IF EXISTS persona;
DROP TABLE IF EXISTS mcelular;
DROP TABLE IF EXISTS proveedor;
DROP TABLE IF EXISTS talle;
DROP TABLE IF EXISTS auditoria_precio;
DROP TABLE IF EXISTS zapato;

CREATE TABLE zapato (
    MODELO VARCHAR(30) NOT NULL,
    COLOR VARCHAR(30) NOT NULL,
    PRECIO DECIMAL(10,2) NOT NULL,

    PRIMARY KEY (MODELO, COLOR),

    CONSTRAINT control_precio CHECK (PRECIO > 0 AND PRECIO < 200000)
);


CREATE TABLE auditoria_precio (
    ID_AUDITORIA INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    MODELO VARCHAR(30) NOT NULL,
    COLOR VARCHAR(30) NOT NULL,
    FECHA DATETIME NOT NULL,
    PRECIO_ANTERIOR DECIMAL(10,2) NOT NULL,
    PRECIO_NUEVO DECIMAL(10,2) NOT NULL,
    USUARIO VARCHAR(288) NOT NULL
);



CREATE TABLE talle (
    NUMERO INT NOT NULL PRIMARY KEY,

    CONSTRAINT NUMERO CHECK (NUMERO > 26 AND NUMERO < 48)
);


CREATE TABLE proveedor (
    CUIT CHAR(11) NOT NULL PRIMARY KEY,
    TEL_FIJO VARCHAR(30) NOT NULL,
    DIRECCION VARCHAR(30) NOT NULL,
    RAZON_SOCIAL VARCHAR(30) NOT NULL
);


CREATE TABLE mcelular (
    CELULAR VARCHAR(30) NOT NULL,
    CUITPROVEEDOR CHAR(11) NOT NULL,

    PRIMARY KEY (CELULAR, CUITPROVEEDOR),

    FOREIGN KEY (CUITPROVEEDOR) REFERENCES proveedor(CUIT)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE persona (
    DNI INT UNSIGNED NOT NULL PRIMARY KEY,
    NOMBRE VARCHAR(30) NOT NULL,
    APELLIDO VARCHAR(30) NOT NULL,
    DIRECCION VARCHAR(30) NOT NULL
);


CREATE TABLE cliente (
    DNI INT UNSIGNED NOT NULL PRIMARY KEY,

    FOREIGN KEY (DNI) REFERENCES persona(DNI)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE mayorista (
    DNI INT UNSIGNED NOT NULL PRIMARY KEY,
    DESCUENTO_GENERAL DECIMAL(5,2) NOT NULL,

    FOREIGN KEY (DNI) REFERENCES cliente(DNI)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CHECK (DESCUENTO_GENERAL BETWEEN 0 AND 100)
);


CREATE TABLE minorista (
    DNI INT UNSIGNED NOT NULL PRIMARY KEY,
    FECHA_NACIMIENTO DATE NOT NULL,

    FOREIGN KEY (DNI) REFERENCES cliente(DNI)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE vendedor (
    NRO_VENDEDOR INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DNI INT UNSIGNED NOT NULL UNIQUE,

    FOREIGN KEY (DNI) REFERENCES persona(DNI)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE venta (
    NUM_FACTURA INT NOT NULL PRIMARY KEY,
    FECHA DATE NOT NULL,
    MONTO DECIMAL(12,2) NOT NULL,
    DNI INT UNSIGNED NOT NULL,
    NRO_VENDEDOR INT UNSIGNED NOT NULL,
    DESCUENTO DECIMAL(5,2) NOT NULL,

    FOREIGN KEY (DNI) REFERENCES cliente(DNI)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    FOREIGN KEY (NRO_VENDEDOR) REFERENCES vendedor(NRO_VENDEDOR)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT control_descuento_venta CHECK (DESCUENTO BETWEEN 0 AND 100),

    CONSTRAINT control_monto CHECK (MONTO >= 0)
);


CREATE TABLE franco (
    NRO_FRANCO INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    FECHA DATE NOT NULL,
    OBSERVACION VARCHAR(300),
    NRO_VENDEDOR INT UNSIGNED NOT NULL,

    FOREIGN KEY (NRO_VENDEDOR) REFERENCES vendedor(NRO_VENDEDOR)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE dia (
    NOMBRE_DIA VARCHAR(30) NOT NULL PRIMARY KEY
);


CREATE TABLE tiene (
    MODELO VARCHAR(30) NOT NULL,
    COLOR VARCHAR(30) NOT NULL,
    NUMERO INT NOT NULL,
    CANTIDAD INT UNSIGNED NOT NULL,

    PRIMARY KEY (MODELO, COLOR, NUMERO),

    FOREIGN KEY (MODELO, COLOR) REFERENCES zapato(MODELO, COLOR)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    FOREIGN KEY (NUMERO) REFERENCES talle(NUMERO)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE provee (
    MODELO VARCHAR(30) NOT NULL,
    COLOR VARCHAR(30) NOT NULL,
    CUIT CHAR(11) NOT NULL,

    PRIMARY KEY (MODELO, COLOR, CUIT),

    FOREIGN KEY (MODELO, COLOR) REFERENCES zapato(MODELO, COLOR)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    FOREIGN KEY (CUIT) REFERENCES proveedor(CUIT)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


CREATE TABLE vendido (
    NUM_FACTURA INT NOT NULL,
    MODELO VARCHAR(30) NOT NULL,
    COLOR VARCHAR(30) NOT NULL,
    NUMERO INT NOT NULL,
    CANT_VENDIDO INT UNSIGNED NOT NULL,
    PRECIO_VENTA DECIMAL(10,2) NOT NULL,

    PRIMARY KEY (NUM_FACTURA, MODELO, COLOR, NUMERO),

    FOREIGN KEY (NUM_FACTURA) REFERENCES venta(NUM_FACTURA)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    FOREIGN KEY (MODELO, COLOR, NUMERO) REFERENCES tiene(MODELO, COLOR, NUMERO)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);


CREATE TABLE horario (
    NOMBRE_DIA VARCHAR(30) NOT NULL,
    NRO_VENDEDOR INT UNSIGNED NOT NULL,
    H_ENTRADA TIME NOT NULL,
    H_SALIDA TIME NOT NULL,

    PRIMARY KEY (NOMBRE_DIA, NRO_VENDEDOR),

    FOREIGN KEY (NOMBRE_DIA) REFERENCES dia(NOMBRE_DIA)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    FOREIGN KEY (NRO_VENDEDOR) REFERENCES vendedor(NRO_VENDEDOR)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);


DELIMITER $$

CREATE TRIGGER auditoria_cambio_precio
AFTER UPDATE ON zapato
FOR EACH ROW
BEGIN
    IF OLD.PRECIO <> NEW.PRECIO THEN
        INSERT INTO auditoria_precio (
            MODELO,
            COLOR,
            FECHA,
            PRECIO_ANTERIOR,
            PRECIO_NUEVO,
            USUARIO
        )
        VALUES (
            OLD.MODELO,
            OLD.COLOR,
            NOW(),
            OLD.PRECIO,
            NEW.PRECIO,
            USER()
        );
    END IF;
END$$

DELIMITER ;




